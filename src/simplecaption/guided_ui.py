"""One visible workflow, with optional expert controls kept out of the way."""
from PySide6.QtCore import Qt
from PySide6.QtMultimedia import QAudioOutput, QMediaPlayer
from PySide6.QtMultimediaWidgets import QVideoWidget
from PySide6.QtWidgets import (
    QCheckBox, QFrame, QHBoxLayout, QHeaderView, QLabel, QProgressBar,
    QPushButton, QSlider, QSplitter, QTableWidget, QVBoxLayout, QWidget,
)


def build_guided_ui(window):
    from simplecaption.window import DropCard, _SOURCE_LANGS, _TARGET_LANGS, _QUALITIES

    root = QVBoxLayout(window)
    root.setContentsMargins(24, 20, 24, 20)
    root.setSpacing(12)
    title = QLabel("视频翻译")
    title.setObjectName("iosLargeTitle")
    root.addWidget(title)
    intro = QLabel("① 选择视频   →   ② 一键翻译   →   ③ 校对并导出\n识别的是声音中的对白；画面文字识别请在高级工作站使用。原视频保持不变。")
    intro.setWordWrap(True)
    root.addWidget(intro)
    window.drop = DropCard()
    window.drop.set_handler(window._browse)
    layout = QVBoxLayout(window.drop)
    window.drop_label = QLabel("① 将视频拖到这里，或点击选择文件")
    window.drop_label.setAlignment(Qt.AlignmentFlag.AlignCenter)
    window.drop_label.setWordWrap(True)
    layout.addWidget(window.drop_label)
    root.addWidget(window.drop)

    controls = QHBoxLayout()
    controls.addWidget(QLabel("翻译成"))
    window.target_combo = window._combo(_TARGET_LANGS, "en")
    controls.addWidget(window.target_combo)
    window.start_button = QPushButton("② 开始翻译")
    window.start_button.setMinimumHeight(42)
    window.start_button.setObjectName("startTranslateButton")
    window.start_button.clicked.connect(window.start_pipeline)
    controls.addWidget(window.start_button, 1)
    window.stop_button = QPushButton("当前步骤完成后停止")
    window.stop_button.clicked.connect(window.stop_after_stage)
    controls.addWidget(window.stop_button)
    root.addLayout(controls)
    window.stage_label = QLabel("等待选择视频")
    root.addWidget(window.stage_label)
    window.progress = QProgressBar()
    window.progress.setRange(0, 100)
    root.addWidget(window.progress)

    splitter = QSplitter(Qt.Orientation.Horizontal)
    preview = QWidget()
    player_layout = QVBoxLayout(preview)
    player_layout.setContentsMargins(0, 0, 0, 0)
    player_layout.addWidget(QLabel("原视频预览 · 点击字幕定位，译文请在右侧校对"))
    window.video_widget = QVideoWidget()
    window.video_widget.setMinimumHeight(180)
    player_layout.addWidget(window.video_widget, 1)
    window.player = QMediaPlayer(window)
    window.audio = QAudioOutput(window)
    window.player.setAudioOutput(window.audio)
    window.player.setVideoOutput(window.video_widget)
    playback = QHBoxLayout()
    window.play_button = QPushButton("播放 / 暂停")
    window.play_button.clicked.connect(window.toggle_playback)
    playback.addWidget(window.play_button)
    window.seek_slider = QSlider(Qt.Orientation.Horizontal)
    window.player.durationChanged.connect(lambda value: window.seek_slider.setRange(0, int(value)))
    window.player.positionChanged.connect(lambda value: window.seek_slider.setValue(int(value)) if not window.seek_slider.isSliderDown() else None)
    window.seek_slider.sliderMoved.connect(window.player.setPosition)
    window.player.errorOccurred.connect(lambda *_: window.status.setText("预览无法播放此文件；仍可尝试识别翻译，或换用 MP4 视频。"))
    playback.addWidget(window.seek_slider, 1)
    player_layout.addLayout(playback)
    splitter.addWidget(preview)
    editor = QWidget()
    editor_layout = QVBoxLayout(editor)
    editor_layout.setContentsMargins(0, 0, 0, 0)
    editor_layout.addWidget(QLabel("③ 双击修改原文或译文 · 时间暂不在此编辑"))
    window.table = QTableWidget(0, 4)
    window.table.setHorizontalHeaderLabels(["开始", "结束", "原文", "译文（可修改）"])
    window.table.setSelectionBehavior(QTableWidget.SelectionBehavior.SelectRows)
    window.table.setEditTriggers(QTableWidget.EditTrigger.DoubleClicked | QTableWidget.EditTrigger.EditKeyPressed)
    header = window.table.horizontalHeader()
    for column in (0, 1):
        header.setSectionResizeMode(column, QHeaderView.ResizeMode.ResizeToContents)
    for column in (2, 3):
        header.setSectionResizeMode(column, QHeaderView.ResizeMode.Stretch)
    window.table.itemChanged.connect(window._on_caption_edited)
    window.table.cellClicked.connect(window.seek_caption)
    editor_layout.addWidget(window.table, 1)
    splitter.addWidget(editor)
    splitter.setSizes([400, 600])
    root.addWidget(splitter, 1)

    exports = QHBoxLayout()
    window.export_button = QPushButton("保存译文字幕 .srt")
    window.export_button.clicked.connect(window.export_subtitles)
    exports.addWidget(window.export_button)
    window.cover_button = QPushButton("导出带字幕的视频…")
    window.cover_button.clicked.connect(window.start_cover)
    exports.addWidget(window.cover_button)
    window.folder_button = QPushButton("打开结果文件夹")
    window.folder_button.clicked.connect(window.open_output_folder)
    exports.addWidget(window.folder_button)
    root.addLayout(exports)

    window.advanced_toggle = QCheckBox("高级选项（通常不需要修改）")
    root.addWidget(window.advanced_toggle)
    window.advanced_panel = QFrame()
    advanced = QVBoxLayout(window.advanced_panel)
    window.source_combo = window._combo(_SOURCE_LANGS, "auto")
    window.quality_combo = window._combo(_QUALITIES, "standard")
    advanced.addLayout(window._row("对白语言", window.source_combo))
    advanced.addLayout(window._row("离线翻译档位", window.quality_combo))
    window.hint = QLabel()
    window.hint.setWordWrap(True)
    advanced.addWidget(window.hint)
    window.quality_combo.currentIndexChanged.connect(window._refresh_hint)
    window.blur_checkbox = QCheckBox("导出时遮挡底部原字幕（固定区域马赛克，会遮挡画面）")
    advanced.addWidget(window.blur_checkbox)
    separate = QHBoxLayout()
    window.transcribe_button = QPushButton("仅识别 / 重新识别")
    window.transcribe_button.clicked.connect(window.start_transcription)
    separate.addWidget(window.transcribe_button)
    window.translate_button = QPushButton("仅翻译 / 重新翻译")
    window.translate_button.clicked.connect(window.confirm_retranslation)
    separate.addWidget(window.translate_button)
    window.full_button = QPushButton("打开高级工作站…")
    window.full_button.clicked.connect(window.open_full_mode)
    separate.addWidget(window.full_button)
    advanced.addLayout(separate)
    advanced.addWidget(QLabel("高级工作站含 OCR、时间轴、批量处理和模型管理。打开后本窗口隐藏，关闭工作站返回。"))
    root.addWidget(window.advanced_panel)
    window.advanced_panel.hide()
    window.advanced_toggle.toggled.connect(window.advanced_panel.setVisible)
    window.status = QLabel("请选择视频。")
    window.status.setWordWrap(True)
    window.status.setTextInteractionFlags(Qt.TextInteractionFlag.TextSelectableByMouse)
    root.addWidget(window.status)
    window.target_combo.currentIndexChanged.connect(window._target_changed)
    window.source_combo.currentIndexChanged.connect(window._source_changed)
    window._sync_buttons()
